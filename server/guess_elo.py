def game_moves_san(pgn: str) -> list[str]:
    """SAN move list for the frontend board replay."""
    game = chess.pgn.read_game(io.StringIO(pgn))
    if game is None:
        return []
    board = game.board()
    out: list[str] = []
    for move in game.mainline_moves():
        out.append(board.san(move))
        board.push(move)
    return out


def duel_public(
    conn: sqlite3.Connection, duel: sqlite3.Row, user_id: int
) -> dict[str, object]:
    """Serialize a duel for its participant. The true rating and the opponent's
    guess are only revealed once the duel is ``done``."""
    side = side_of(duel, user_id)
    game = conn.execute(
        "SELECT pgn, plies FROM elo_games WHERE id = ?", (int(duel["game_id"]),)
    ).fetchone()
    my_guess = duel["guess_a"] if side == "a" else duel["guess_b"]
    opp_guess = duel["guess_b"] if side == "a" else duel["guess_a"]
    done = duel["status"] == "done"
    payload: dict[str, object] = {
        "duel_id": int(duel["id"]),
        "you": side,
        "status": duel["status"],
        "deadline_ts": int(duel["deadline_ts"]),
        "is_bot": bool(duel["is_bot"]),
        "opponent": "Bot" if duel["is_bot"] else "Opponent",
        "pgn": game["pgn"] if game else "",
        "moves": game_moves_san(game["pgn"]) if game else [],
        "your_guess": my_guess,
        "opponent_guessed": opp_guess is not None,
        "guess_min": GUESS_MIN,
        "guess_max": GUESS_MAX,
    }
    if done:
        winner_side = duel["winner"]
        outcome = "draw" if winner_side == "draw" else ("win" if winner_side == side else "loss")
        payload.update(
            {
                "true_elo": int(duel["true_elo"]),
                "opponent_guess": opp_guess,
                "winner": winner_side,
                "outcome": outcome,
                "your_points": guess_points(int(duel["true_elo"]), my_guess),
                "opponent_points": guess_points(int(duel["true_elo"]), opp_guess),
            }
        )
    return payload


